// Dynamic calculation helpers for runtime render
export function computeSafetyStatus(available, incoming = 0, minThreshold = 0, openDemand = 0) {
  const projected = available + incoming - openDemand;
  if (projected < minThreshold || available < minThreshold) return 'critical';
  if (projected < minThreshold * 1.2) return 'low';
  return 'healthy';
}

